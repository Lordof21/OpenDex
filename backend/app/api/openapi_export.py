"""The PUBLIC OpenAPI document of the OpenDeX backend (docs/api/openapi.json).

FastAPI already derives a schema from the routes (``app.openapi()``); this module turns it into something a third party
can build a client against:

  * only the versioned ``/api/v1/*`` surface — every route is also served unversioned under ``/api/*`` (the bundled UI
    uses that alias and it always tracks the latest version); one copy of each operation is enough in the document,
  * the rules that are NOT visible in the routes because middleware enforces them: bearer-token authentication
    (api/auth.py), the browser Origin/Host guard (api/origin_guard.py), the body limit and the security headers
    (api/hardening.py) — as security schemes and shared error responses,
  * descriptions for the tag groups.

``app.openapi()`` itself is left alone: tests/test_route_manifest.py pins the frontend contract on it.
The document is regenerated by ``python scripts/export_openapi.py`` and kept honest by tests/test_openapi_snapshot.py.
"""
from __future__ import annotations

import copy
from typing import Any

from fastapi import APIRouter, FastAPI
from fastapi.routing import APIRoute

from .deps import get_active_serial
from .v1.endpoints import apps, audio, devices, diagnostics, fs, input, notifications, pairing, settings, telemetry, windows

# The endpoint routers api/v1/router.py mounts. Their `routes` are plain APIRoute objects whatever the FastAPI version
# (the mounted app's own route list is a tree of lazily included routers on recent versions) — so the per-route facts the
# schema cannot show (the bound-device guard) are read from these. tests/test_openapi_snapshot.py pins that the list is complete.
ENDPOINT_ROUTERS: tuple[APIRouter, ...] = tuple(
    module.router for module in (devices, pairing, apps, windows, settings, audio, input, notifications, diagnostics, telemetry, fs)
)

PUBLIC_PREFIX = "/api/v1"
REPOSITORY_URL = "https://github.com/Lordof21/OpenDex"
DEFAULT_SERVER = "http://127.0.0.1:8710"

# Served without a token (api/auth.py EXEMPT_PATHS): liveness for the boot splash / Docker, and the opt-in token handout.
PUBLIC_OPERATIONS = frozenset({f"{PUBLIC_PREFIX}/health", f"{PUBLIC_PREFIX}/auth/bootstrap"})
_BODY_METHODS = frozenset({"post", "put", "patch"})
_HTTP_METHODS = frozenset({"get", "post", "put", "patch", "delete"})

DESCRIPTION = f"""\
The local control API of the **OpenDeX backend** — the process that drives an Android phone over `adb` and the patched
scrcpy server, and that the desktop UI talks to. It listens on `127.0.0.1:8710` by default.

### Authentication
Every `/api/*` request and every `/ws/*` handshake must present the API token — one secret per user, read from
`OPENDEX_API_TOKEN` or the file `~/.opendex/api-token` (created with mode 0600 on first start):

* `Authorization: Bearer <token>` (preferred), or
* a `token` query parameter — **only** on `GET` requests and WebSocket handshakes (browsers cannot set headers on those).

A missing/wrong token is `401` (HTTP) or WebSocket close code `4401`, before any route runs. Only `GET /health` and, when
`OPENDEX_TOKEN_BOOTSTRAP` is enabled, `GET /auth/bootstrap` are exempt.

### Browser protection
A request that carries an `Origin` header that is not one of the app's own origins is refused with `403` (WebSocket: close
code `4403`); so is a `Host` header that is not a loopback / `*.localhost` name (DNS rebinding). Clients without an `Origin`
header (curl, scripts) are not affected — they still need the token.

### Limits
Request bodies are capped (`OPENDEX_MAX_BODY_BYTES`, default 2 MB): `413` when the declared `Content-Length` is larger, `411` when a
body is sent chunked without a `Content-Length`, `400` when the declared length is not a number. Responses are never cached (`Cache-Control: no-store`).

### Versioning
`/api/v1/*` is the versioned surface. The same operations are also served unversioned as `/api/*` (an alias that tracks the
latest version — what the bundled UI calls). Breaking changes will get a new version prefix.

### Not described here
Real-time channels are WebSockets, which OpenAPI cannot describe: `/ws/events` (JSON events), `/ws/video/{{window_id}}`,
`/ws/audio`, `/ws/audio/{{window_id}}` (binary media) and `/ws/input/{{window_id}}` (JSON touch/keyboard messages). They are
specified in [docs/API.md]({REPOSITORY_URL}/blob/main/docs/API.md).
"""

