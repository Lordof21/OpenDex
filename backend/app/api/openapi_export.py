def _needs_device(route: APIRoute) -> bool:
    """True when the route (or the router it came from) depends on the bound-device guard (api/deps.py)."""
    stack = list(route.dependant.dependencies)
    while stack:
        dep = stack.pop()
        if dep.call is get_active_serial:
            return True
        stack.extend(dep.dependencies)
    return False


def public_schema(app: FastAPI) -> dict[str, Any]:
    """The documented API: `/api/v1/*` only, enriched with the rules the middleware enforces."""
    spec = copy.deepcopy(app.openapi())

    spec["info"] = {
        "title": "OpenDeX Backend API",
        "version": spec["info"]["version"],
        "summary": "Local control API of the OpenDeX backend (Android multi-window mirroring).",
        "description": DESCRIPTION,
        "license": {"name": "GPL-3.0-or-later", "identifier": "GPL-3.0-or-later"},   # OpenAPI 3.1: identifier XOR url
        "contact": {"name": "OpenDeX on GitHub", "url": REPOSITORY_URL},
    }
    spec["servers"] = [{"url": DEFAULT_SERVER, "description": "Default local listener (OPENDEX_HTTP_HOST / OPENDEX_HTTP_PORT)"}]
    spec["externalDocs"] = {"description": "Conventions, WebSocket protocols and events", "url": f"{REPOSITORY_URL}/blob/main/docs/API.md"}
    spec["tags"] = copy.deepcopy(TAGS)
    spec["security"] = [{"bearerAuth": []}, {"tokenQuery": []}]

    needs_device = {
        (f"{PUBLIC_PREFIX}{route.path}", method.lower())
        for router in ENDPOINT_ROUTERS for route in router.routes if isinstance(route, APIRoute) and _needs_device(route)
        for method in route.methods or ()
    }
    spec["paths"] = {path: ops for path, ops in spec["paths"].items() if path.startswith(f"{PUBLIC_PREFIX}/")}
    for path, ops in spec["paths"].items():
        for method, operation in ops.items():
            if method not in _HTTP_METHODS:
                continue
            responses = operation.setdefault("responses", {})
            if (path, method) in needs_device:
                operation["x-requires-device"] = True
                responses.setdefault("409", {"$ref": "#/components/responses/NoDevice"})
            if path in PUBLIC_OPERATIONS:
                operation["security"] = []
                if path.endswith("/bootstrap"):
                    operation["description"] = (operation.get("description") or "").strip() or (
                        "Hands the API token to a browser page from one of the app's own origins. Disabled unless "
                        "`OPENDEX_TOKEN_BOOTSTRAP=true` (the Docker/nginx deployment); the desktop build leaves it off. "
                        "An `Origin` header is required — non-browser clients read the token file instead."
                    )
                responses.setdefault("403", {"$ref": "#/components/responses/ForeignOrigin"})
                continue
            responses.setdefault("401", {"$ref": "#/components/responses/Unauthorized"})
            responses.setdefault("403", {"$ref": "#/components/responses/ForeignOrigin"})
            if method in _BODY_METHODS:
                responses.setdefault("411", {"$ref": "#/components/responses/LengthRequired"})
                responses.setdefault("413", {"$ref": "#/components/responses/PayloadTooLarge"})

    components = spec.setdefault("components", {})
    components["securitySchemes"] = copy.deepcopy(SECURITY_SCHEMES)
    components["responses"] = copy.deepcopy(RESPONSES)
    components.setdefault("schemas", {})["ErrorDetail"] = copy.deepcopy(ERROR_DETAIL_SCHEMA)
    components["schemas"] = dict(sorted(components["schemas"].items()))
    return spec
